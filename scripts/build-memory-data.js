const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const tangPath = process.argv[2] || '/tmp/tang300.json'
const idiomPath = process.argv[3] || '/tmp/idiom.json'
const tangPoems = JSON.parse(fs.readFileSync(tangPath, 'utf8'))
const idioms = JSON.parse(fs.readFileSync(idiomPath, 'utf8'))

const poetryLibrary = tangPoems.map(poem => ({
  id: `tang-${poem.id}`,
  title: String(poem.title || '').trim(),
  author: String(poem.author || '').trim(),
  form: String(poem.type || '').trim(),
  body: String(poem.contents || '').trim()
}))

const idiomLibrary = [...new Set(idioms
  .map(item => String(item.word || '').trim())
  .filter(word => /^[\p{Script=Han}]{4,8}$/u.test(word)))]

const poetryMemoryTexts = [...new Set(poetryLibrary
  .flatMap(poem => poem.body.split(/[\n，。！？；：、]/))
  .map(text => text.replace(/[^\p{Script=Han}]/gu, ''))
  .filter(text => text.length >= 4 && text.length <= 16))]

